#!/usr/bin/env node
/**
 * scripts/model-catalog/build-hub-map.mjs
 *
 * Emits the EdgeOne Hub copy of the two lookup tables the per-model capability
 * query needs:
 *
 *   shared/model-catalog/provider-map.json -> edgeone-hub/lib/generated-model-map.js
 *   shared/model-catalog/overrides.json    -> (same module, OVERRIDES)
 *
 * The Hub runs in a Web Standard runtime (no node:fs), so the tables are frozen
 * into a JS module the same way shared/presets/build-catalog.mjs freezes
 * generated-presets.js. Both sources stay the single source of truth; only the
 * `providers` map and the `models` overrides are copied — `_comment` / `_gaps`
 * are documentation and would only cost edge bundle bytes.
 *
 * Output is deterministic: key order follows the source files, and the runtime
 * lookup never depends on it (exact match first, then a case-insensitive scan
 * that takes the lexicographically smallest id, mirroring the Go resolver).
 *
 * Build-time script: node:fs is allowed here and nowhere in edge code.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(__dirname, '..', '..');

export const SHARED_CATALOG_DIR = join(projectRoot, 'shared/model-catalog');
export const HUB_MODULE_PATH = join(projectRoot, 'edgeone-hub/lib/generated-model-map.js');

function compact(value) {
  return JSON.stringify(value);
}

export function renderHubMapModule(providerMapDoc, overridesDoc) {
  const providers = providerMapDoc && typeof providerMapDoc.providers === 'object' && providerMapDoc.providers
    ? providerMapDoc.providers
    : {};
  const overrides = overridesDoc && typeof overridesDoc.models === 'object' && overridesDoc.models
    ? overridesDoc.models
    : {};
  // Unwrapped, like the Go Catalog's internal providerMap/overrides fields: the
  // lookup then takes a preset id / "<preset>/<model>" key directly instead of
  // every call site re-navigating a document wrapper.
  return `/**
 * Provider map + manual overrides for the Hub's per-model capability lookup.
 * Generated by scripts/model-catalog/build-hub-map.mjs from
 * shared/model-catalog/{provider-map,overrides}.json; do not edit directly.
 */
export const PROVIDER_MAP = ${compact(providers)};
export const OVERRIDES = ${compact(overrides)};
`;
}

function main() {
  const providerMapDoc = JSON.parse(readFileSync(join(SHARED_CATALOG_DIR, 'provider-map.json'), 'utf8'));
  const overridesDoc = JSON.parse(readFileSync(join(SHARED_CATALOG_DIR, 'overrides.json'), 'utf8'));
  const content = renderHubMapModule(providerMapDoc, overridesDoc);
  writeFileSync(HUB_MODULE_PATH, content, 'utf8');
  const presetCount = Object.keys(providerMapDoc.providers || {}).length;
  const overrideCount = Object.keys(overridesDoc.models || {}).length;
  console.log(
    `   ✓ edgeone-hub/lib/generated-model-map.js (${presetCount} presets, ${overrideCount} overrides, ${Buffer.byteLength(content, 'utf8')} bytes)`
  );
}

const invokedDirectly = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (invokedDirectly) main();